#!/usr/bin/env python3
"""Package a Markdown story project as an Obsidian-ready zip.

The zip contains a single top-level vault folder, Markdown/Canvas/image
resources, a generated OPEN_IN_OBSIDIAN.md, and a manifest. Sensitive
or unrelated files (.env, .git, raw word lists, caches) are excluded.

Usage:
  python package_story.py --source stories/my-story --out my-story-obsidian.zip
  python package_story.py --source stories/my-story --out out.zip --name "My Story Vault"
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ALLOWED_SUFFIXES = {
    ".md",
    ".canvas",
    ".png",
    ".jpg",
    ".jpeg",
    ".webp",
    ".gif",
    ".svg",
    ".css",
}
EXCLUDED_DIRS = {
    ".git",
    ".obsidian",
    ".dsh",
    ".claude",
    ".trash",
    "node_modules",
    "__pycache__",
    ".venv",
    "venv",
    "data/raw",
}
EXCLUDED_NAMES = {".env", ".DS_Store", "Thumbs.db"}


def safe_vault_name(value: str) -> str:
    name = value.strip().strip(".")
    name = re.sub(r"[\x00-\x1f<>:\"/\\|?*]+", "-", name)
    name = re.sub(r"\s+", " ", name).strip(" .-")
    if not name:
        raise SystemExit("--name 不能为空或仅包含非法字符")
    return name[:100]


def is_excluded(rel: Path) -> bool:
    posix = rel.as_posix()
    parts = set(rel.parts)
    if parts & {".git", ".obsidian", ".dsh", ".claude", ".trash", "node_modules", "__pycache__", ".venv", "venv"}:
        return True
    if posix.startswith("data/raw/"):
        return True
    if rel.name in EXCLUDED_NAMES or rel.name.startswith(".env"):
        return True
    if rel.suffix.lower() not in ALLOWED_SUFFIXES:
        return True
    return False


def collect_files(source: Path) -> list[Path]:
    source = source.resolve()
    files = []
    for p in source.rglob("*"):
        if not p.is_file():
            continue
        try:
            rel = p.relative_to(source)
        except ValueError:
            continue
        if is_excluded(rel):
            continue
        try:
            p.resolve().relative_to(source)
        except ValueError:
            continue
        files.append(rel)
    return sorted(files, key=lambda p: p.as_posix().lower())


def reading_order(files: list[Path]) -> list[Path]:
    def score(p: Path) -> tuple:
        s = p.as_posix()
        if s == "README.md":
            return (0, s)
        if s.startswith("stories/") and s.endswith(".md"):
            return (1, s)
        if s in {"00_novel_bible.md", "01_vocabulary_ledger.md", "02_progress_ledger.md"}:
            return (2, s)
        if p.suffix.lower() == ".md" and not s.startswith("CONTINUE"):
            return (3, s)
        return (4, s)

    return sorted([p for p in files if p.suffix.lower() == ".md"], key=score)


def build_open_file(vault_name: str, files: list[Path]) -> str:
    ordered = reading_order(files)
    lines = [
        "# Open this story in Obsidian",
        "",
        "1. Unzip the archive.",
        f"2. In Obsidian choose **Open folder as vault** and select `{vault_name}`.",
        "3. Start from the reading order below.",
        "4. To continue in a new AI chat, give the assistant `RESUME_CONTEXT.md` (or this vault).",
        "",
        "## Reading order",
        "",
    ]
    if ordered:
        for p in ordered:
            lines.append(f"- `{p.as_posix()}`")
    else:
        lines.append("- No Markdown files were included.")
    lines += [
        "",
        "## New-conversation handoff",
        "",
        "The portable vault may include:",
        "- `RESUME_CONTEXT.md` — a compact state file to attach or paste into a new chat.",
        "- `CONTINUE_HERE.md` — a fuller continuity note for the assistant.",
        "- `OPEN_IN_OBSIDIAN.md` — this file.",
        "",
        "Do not treat missing files as canon; the current story files are the source of truth.",
        "",
        "---",
        "",
        "*Generated by Vocab Novel Studio portable packager.*",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Package a Markdown story project as an Obsidian-ready zip")
    ap.add_argument("--source", required=True, help="故事项目目录")
    ap.add_argument("--out", required=True, help="输出 .zip 路径")
    ap.add_argument("--name", help="解压后的顶层 Vault 文件夹名；默认取源目录名")
    args = ap.parse_args()

    source = Path(args.source).expanduser().resolve()
    if not source.is_dir():
        raise SystemExit(f"源目录不存在：{source}")
    vault_name = safe_vault_name(args.name or source.name)
    out = Path(args.out).expanduser().resolve()
    if out.suffix.lower() != ".zip":
        out = out.with_suffix(".zip")
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.is_relative_to(source):
        raise SystemExit("输出 zip 不能放在源目录内，避免把压缩包再次打包。")

    files = collect_files(source)
    if not files:
        raise SystemExit("源目录中没有可打包的 Markdown/Canvas/图片文件。")

    with tempfile.TemporaryDirectory(prefix="vocab_story_pack_") as tmp:
        stage_root = Path(tmp) / vault_name
        stage_root.mkdir(parents=True)
        for rel in files:
            dest = stage_root / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source / rel, dest)

        open_file = stage_root / "OPEN_IN_OBSIDIAN.md"
        if not open_file.exists():
            open_file.write_text(build_open_file(vault_name, files + [Path("OPEN_IN_OBSIDIAN.md")]), encoding="utf-8")

        resume_exists = (stage_root / "RESUME_CONTEXT.md").exists()
        continue_exists = (stage_root / "CONTINUE_HERE.md").exists()
        manifest = {
            "vault_folder": vault_name,
            "source": str(source),
            "packaged_at": datetime.now(timezone.utc).isoformat(),
            "files": [f"{vault_name}/{p.as_posix()}" for p in files] + [f"{vault_name}/OPEN_IN_OBSIDIAN.md"],
            "resume_context_included": resume_exists,
            "continue_here_included": continue_exists,
            "note": "Open the top-level folder as an Obsidian vault. Attach RESUME_CONTEXT.md to continue in a new chat.",
        }
        (stage_root / "PORTABLE_MANIFEST.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
        )

        with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            for p in sorted(stage_root.rglob("*")):
                if p.is_file():
                    arcname = f"{vault_name}/{p.relative_to(stage_root).as_posix()}"
                    zf.write(p, arcname)

    summary = {
        "zip": str(out),
        "vault_folder": vault_name,
        "included_files": len(files) + 1,
        "resume_context_included": resume_exists,
        "continue_here_included": continue_exists,
        "warning": None
        if resume_exists
        else "未找到 RESUME_CONTEXT.md；新对话将缺少可粘贴的续写上下文，请先让 agent 补写。",
        "obsidian_instruction": "Unzip, then Open folder as vault and select the top-level folder.",
    }
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
